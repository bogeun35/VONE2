"""Builds source-fplut-math.js from the installed game's Quantum FPLut assets.

Read-only: resources.assets TextAssets 'FPSinCos' (body 4908336, 411775 int32
pairs sin,cos) and 'FPAcos' (body 423232, 131073 int64). The sine half already
lives in source-updownlift-math.js; this adds the cosine half and acos.
  cos: first value 65536, then 2-bit packed deltas (delta+1 in 0..2).
  acos: first value 205887, then zigzag varint deltas.
Run from reference-analysis/source-migration: python -I extract-fplut-native-data.py
"""
import base64
import hashlib
import pathlib
import struct

ASSETS = pathlib.Path('D:/SteamLibrary/steamapps/common/PICO PARK 2/pico_park_2_Data/resources.assets')
SINCOS_BODY, SINCOS_COUNT = 4908336, 411775
ACOS_BODY, ACOS_COUNT = 423232, 131073

b = ASSETS.read_bytes()
assert b[SINCOS_BODY - 12:SINCOS_BODY - 4] == b'FPSinCos', 'FPSinCos asset name not found'
assert b[ACOS_BODY - 12:ACOS_BODY - 6] == b'FPAcos', 'FPAcos asset name not found'
pairs = struct.unpack_from('<%di' % (2 * SINCOS_COUNT), b, SINCOS_BODY)
cos = pairs[1::2]
acos = struct.unpack_from('<%dq' % ACOS_COUNT, b, ACOS_BODY)

packed = bytearray((SINCOS_COUNT - 1 + 3) // 4)
for i in range(1, SINCOS_COUNT):
    d = cos[i] - cos[i - 1]
    assert -1 <= d <= 1
    k = i - 1
    packed[k >> 2] |= (d + 1) << ((k & 3) * 2)

var = bytearray()
for i in range(1, ACOS_COUNT):
    d = acos[i] - acos[i - 1]
    z = (d << 1) ^ (d >> 63)
    while True:
        byte = z & 0x7f
        z >>= 7
        if z:
            var.append(byte | 0x80)
        else:
            var.append(byte)
            break

cos_sha = hashlib.sha256(struct.pack('<%di' % SINCOS_COUNT, *cos)).hexdigest()
acos_sha = hashlib.sha256(struct.pack('<%dq' % ACOS_COUNT, *acos)).hexdigest()
js = """/* Quantum FPLut cosine half and acos, exact copies of the installed game's
 * resources.assets TextAssets 'FPSinCos' (body 4908336, the second int32 of each
 * 8-byte pair; the sine half is source-updownlift-math.js) and 'FPAcos'
 * (body 423232, 131073 int64, index = cos raw + 65536). Generated by
 * extract-fplut-native-data.py. SHA256 cos %s, acos %s.
 * sincosRaw(r) mirrors FPMath.SinCos: index |r| mod 0x6487e, sin odd, cos even.
 */
(function(root,factory){const c=typeof module==='object'&&module.exports;const api=factory(c?require('./source-updownlift-math.js'):root.SourceUpDownLiftMath);if(c)module.exports=api;root.SourceFPLutMath=api;})(typeof globalThis!=='undefined'?globalThis:this,function(SinMath){'use strict';
const COS='%s';
const ACOS='%s';
const dec=s=>typeof Buffer!=='undefined'?Buffer.from(s,'base64'):Uint8Array.from(atob(s),c=>c.charCodeAt(0));
let cosT=null,acosT=null;
function cosTable(){if(!cosT){const p=dec(COS);cosT=new Int32Array(%d);let v=65536;cosT[0]=v;for(let i=1;i<cosT.length;i++){const k=i-1;v+=((p[k>>2]>>((k&3)*2))&3)-1;cosT[i]=v;}}return cosT;}
function acosTable(){if(!acosT){const p=dec(ACOS);acosT=new Float64Array(%d);let v=205887,j=0;acosT[0]=v;for(let i=1;i<acosT.length;i++){let z=0,sh=0,b;do{b=p[j++];z+=(b&127)*2**sh;sh+=7;}while(b&128);v+=(z%%2?-(z+1)/2:z/2);acosT[i]=v;}}return acosT;}
function sincosRaw(r){if(!Number.isSafeInteger(r))throw Error('FPLut sincos raw must be a safe integer');const i=Math.abs(r)%%0x6487e,s=SinMath.sinRaw(i),c=cosTable()[i];return [r<0&&s!==0?-s:s,c];}
function acosRaw(x){if(!Number.isInteger(x)||x<-65536||x>65536)throw Error('FPLut acos index outside -1..1');return acosTable()[x+65536];}
return {sincosRaw,acosRaw,cosCount:%d,acosCount:%d,cosSha256:'%s',acosSha256:'%s'};});
""" % (cos_sha, acos_sha, base64.b64encode(bytes(packed)).decode(), base64.b64encode(bytes(var)).decode(),
       SINCOS_COUNT, ACOS_COUNT, SINCOS_COUNT, ACOS_COUNT, cos_sha, acos_sha)
pathlib.Path('source-fplut-math.js').write_text(js, encoding='utf-8')
print('cos', cos_sha[:16], 'acos', acos_sha[:16], 'bytes', len(js))
