"""Builds source-fplut-math.js from the installed game's Quantum FPLut assets.

Read-only: resources.assets TextAssets 'FPSinCos' (body 4908336, 411775 int32
pairs sin,cos), 'FPAcos' (body 423232, 131073 int64) and 'FPAtan' (body 8202552,
397730 int64). The sine half already lives in source-updownlift-math.js; this
adds the cosine half, acos and atan.
  cos: first value 65536, then 2-bit packed deltas (delta+1 in 0..2).
  acos: first value 205887, then zigzag varint deltas.
  atan: first value 0, then plain varint deltas (every delta is 0..109).
Run from reference-analysis/source-migration: python -I extract-fplut-native-data.py
"""
import base64
import hashlib
import pathlib
import struct

ASSETS = pathlib.Path('D:/SteamLibrary/steamapps/common/PICO PARK 2/pico_park_2_Data/resources.assets')
SINCOS_BODY, SINCOS_COUNT = 4908336, 411775
ACOS_BODY, ACOS_COUNT = 423232, 131073
ATAN_BODY, ATAN_COUNT = 8202552, 397730

b = ASSETS.read_bytes()
assert b[SINCOS_BODY - 12:SINCOS_BODY - 4] == b'FPSinCos', 'FPSinCos asset name not found'
assert b[ACOS_BODY - 12:ACOS_BODY - 6] == b'FPAcos', 'FPAcos asset name not found'
assert b[ATAN_BODY - 12:ATAN_BODY - 6] == b'FPAtan', 'FPAtan asset name not found'
assert int.from_bytes(b[ATAN_BODY - 4:ATAN_BODY], 'little') == ATAN_COUNT * 8, 'FPAtan body length'
pairs = struct.unpack_from('<%di' % (2 * SINCOS_COUNT), b, SINCOS_BODY)
cos = pairs[1::2]
acos = struct.unpack_from('<%dq' % ACOS_COUNT, b, ACOS_BODY)
atan = struct.unpack_from('<%dq' % ATAN_COUNT, b, ATAN_BODY)
assert atan[0] == 0

packed = bytearray((SINCOS_COUNT - 1 + 3) // 4)
for i in range(1, SINCOS_COUNT):
    d = cos[i] - cos[i - 1]
    assert -1 <= d <= 1
    k = i - 1
    packed[k >> 2] |= (d + 1) << ((k & 3) * 2)

var = bytearray()
for i in range(1, ACOS_COUNT):
    d = acos[i] - acos[i - 1]
    z = (d << 1) ^ (d >> 63)
    while True:
        byte = z & 0x7f
        z >>= 7
        if z:
            var.append(byte | 0x80)
        else:
            var.append(byte)
            break

avar = bytearray()
for i in range(1, ATAN_COUNT):
    z = atan[i] - atan[i - 1]
    assert z >= 0
    while True:
        byte = z & 0x7f
        z >>= 7
        if z:
            avar.append(byte | 0x80)
        else:
            avar.append(byte)
            break

cos_sha = hashlib.sha256(struct.pack('<%di' % SINCOS_COUNT, *cos)).hexdigest()
acos_sha = hashlib.sha256(struct.pack('<%dq' % ACOS_COUNT, *acos)).hexdigest()
atan_sha = hashlib.sha256(struct.pack('<%dq' % ATAN_COUNT, *atan)).hexdigest()
js = """/* Quantum FPLut cosine half, acos and atan, exact copies of the installed game's
 * resources.assets TextAssets 'FPSinCos' (body 4908336, the second int32 of each
 * 8-byte pair; the sine half is source-updownlift-math.js), 'FPAcos'
 * (body 423232, 131073 int64, index = cos raw + 65536) and 'FPAtan' (body
 * 8202552, 397730 int64). Generated by extract-fplut-native-data.py.
 * SHA256 cos %s, acos %s, atan %s.
 * sincosRaw(r) mirrors FPMath.SinCos: index |r| mod 0x6487e, sin odd, cos even.
 * acosRaw(x) is FPMath.Acos 0x181640760 inside -1..1 (outside, the native
 * function returns FP.MinValue; callers handle that themselves).
 * atanRaw(x) mirrors FPMath.Atan 0x1816407f0: |x| <= 6 direct, <= 250 in 1/16
 * steps from 0x60000, <= 10000 in 16-unit steps from 0x60f40, beyond: last entry.
 */
(function(root,factory){const c=typeof module==='object'&&module.exports;const api=factory(c?require('./source-updownlift-math.js'):root.SourceUpDownLiftMath);if(c)module.exports=api;root.SourceFPLutMath=api;})(typeof globalThis!=='undefined'?globalThis:this,function(SinMath){'use strict';
const COS='%s';
const ACOS='%s';
const ATAN='%s';
const dec=s=>typeof Buffer!=='undefined'?Buffer.from(s,'base64'):Uint8Array.from(atob(s),c=>c.charCodeAt(0));
let cosT=null,acosT=null,atanT=null;
function cosTable(){if(!cosT){const p=dec(COS);cosT=new Int32Array(%d);let v=65536;cosT[0]=v;for(let i=1;i<cosT.length;i++){const k=i-1;v+=((p[k>>2]>>((k&3)*2))&3)-1;cosT[i]=v;}}return cosT;}
function acosTable(){if(!acosT){const p=dec(ACOS);acosT=new Float64Array(%d);let v=205887,j=0;acosT[0]=v;for(let i=1;i<acosT.length;i++){let z=0,sh=0,b;do{b=p[j++];z+=(b&127)*2**sh;sh+=7;}while(b&128);v+=(z%%2?-(z+1)/2:z/2);acosT[i]=v;}}return acosT;}
function atanTable(){if(!atanT){const p=dec(ATAN);atanT=new Float64Array(%d);let v=0,j=0;for(let i=1;i<atanT.length;i++){let z=0,sh=0,b;do{b=p[j++];z+=(b&127)*2**sh;sh+=7;}while(b&128);v+=z;atanT[i]=v;}}return atanT;}
function sincosRaw(r){if(!Number.isSafeInteger(r))throw Error('FPLut sincos raw must be a safe integer');const i=Math.abs(r)%%0x6487e,s=SinMath.sinRaw(i),c=cosTable()[i];return [r<0&&s!==0?-s:s,c];}
function acosRaw(x){if(!Number.isInteger(x)||x<-65536||x>65536)throw Error('FPLut acos index outside -1..1');return acosTable()[x+65536];}
function atanRaw(x){if(!Number.isSafeInteger(x))throw Error('FPLut atan raw must be a safe integer');const a=Math.abs(x),t=atanTable();
 const i=a<0x60001?a:a<0xfa0001?Math.floor((a-0x60000)/4096)+0x60000:a>0x27100000?t.length-1:Math.floor((a-0xfa0000)/1048576)+0x60f40;return x<0?-t[i]:t[i];}
return {sincosRaw,acosRaw,atanRaw,cosCount:%d,acosCount:%d,atanCount:%d,cosSha256:'%s',acosSha256:'%s',atanSha256:'%s'};});
""" % (cos_sha, acos_sha, atan_sha, base64.b64encode(bytes(packed)).decode(), base64.b64encode(bytes(var)).decode(), base64.b64encode(bytes(avar)).decode(),
       SINCOS_COUNT, ACOS_COUNT, ATAN_COUNT, SINCOS_COUNT, ACOS_COUNT, ATAN_COUNT, cos_sha, acos_sha, atan_sha)
pathlib.Path('source-fplut-math.js').write_text(js, encoding='utf-8')
print('cos', cos_sha[:16], 'acos', acos_sha[:16], 'atan', atan_sha[:16], 'bytes', len(js))
